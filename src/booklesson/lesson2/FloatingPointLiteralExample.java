package booklesson.lesson2;

public class FloatingPointLiteralExample {
    public static void main(String[] args) {
        double pi = 3.1416;
        System.out.println("Pi = " + pi);
      //  double gravitationalConstant = 6.67408E - 11;//Remove the space between E and the exponent:

        double gravitationalConstant = 6.67408E-11;
        System.out.println("gravitationalConstant = " + gravitationalConstant);

        float area = 50.26544f;
        System.out.println("area = " + area);
    }
}

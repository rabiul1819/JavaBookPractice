package booklesson.lesson2;

public class IntegerLiteralExample {
    public static void main(String[] args) {
        int decimalValue = 123;
        int hexDecimalValue = 0x7B;
        int binaryValue = 0b1111011;
        int octalValue = 0173;
        System.out.println("decimalValue = " + decimalValue );
        System.out.println("hexDecimalValue = " + hexDecimalValue );
        System.out.println("binaryValue = " + binaryValue );
        System.out.println("octalValue = " + octalValue);
    }
}
